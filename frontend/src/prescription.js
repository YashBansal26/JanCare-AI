const HI = {
  'After food': 'खाने के बाद', 'Before food': 'खाने से पहले', 'With food': 'खाने के साथ', 'Empty stomach': 'खाली पेट', 'At bedtime': 'सोते समय',
  morning: 'सुबह', afternoon: 'दोपहर', night: 'रात', sos: 'ज़रूरत पड़ने पर',
};
export const trRx = (text, language) => (language === 'hi' && HI[text]) || text;

// "1-0-1" -> { morning: 1, afternoon: 0, night: 1 }
export function parseDose(dose) {
  if (!dose || dose.toUpperCase() === 'SOS') return { morning: 0, afternoon: 0, night: 0, sos: true };
  const [m = 0, a = 0, n = 0] = dose.split('-').map(x => parseFloat(x) || 0);
  return { morning: m, afternoon: a, night: n, sos: false };
}

const addDays = (dateStr, n) => {
  const d = new Date(`${dateStr}T00:00:00`); d.setDate(d.getDate() + n);
  return d;
};

// Daily timetable: which medicine to take when, and until which date
export function buildSchedule(rx, visitDate) {
  const slots = { morning: [], afternoon: [], night: [], sos: [] };
  for (const m of rx?.medicines || []) {
    const d = parseDose(m.dose);
    const until = m.days ? addDays(visitDate, m.days - 1) : null;
    const item = { ...m, until };
    if (d.sos) slots.sos.push(item);
    for (const k of ['morning', 'afternoon', 'night']) if (d[k] > 0) slots[k].push({ ...item, qty: d[k] });
  }
  return slots;
}

export const isCourseActive = (m, visitDate) => !m.days || addDays(visitDate, m.days) > new Date();

const esc = (s) => String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

